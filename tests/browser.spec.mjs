import { test, expect } from '@playwright/test';
test.use({channel:'chrome'});
test('professor emite, corrige e cancela; consulta pública reflete as alterações',async({page})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:8792/admin');
  await page.getByRole('button',{name:'Emitir certificado'}).click();
  await page.getByLabel('Nome completo do aluno').fill('Aluno de demonstração '+Date.now());
  await page.getByLabel('Graduação recebida').fill('Faixa azul · 1º grau');
  await page.getByLabel('Data da graduação').fill('2026-10-01');
  await page.getByLabel('Responsável pela graduação').fill('Professor de demonstração');
  await page.locator('#certificate-form').getByRole('button',{name:'Emitir certificado'}).click();
  await expect(page.locator('#details')).toBeVisible();
  const url=await page.getByRole('link',{name:'Validar',exact:true}).getAttribute('href');
  expect(url).toMatch(/^https:\/\/vynkor.co\/certificados\/[a-f0-9]{32}$/);
  const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'PNG',exact:true}).click();
  const download=await downloadPromise;expect(download.suggestedFilename()).toMatch(/\.png$/);
  await download.saveAs('test-results/qr-test.png');
  await page.screenshot({path:'test-results/desktop-details.png'});
  await page.getByRole('button',{name:'Corrigir',exact:true}).click();
  await page.getByLabel('Nome completo do aluno').fill('Aluno de demonstração corrigido');
  await page.getByRole('button',{name:'Salvar correção'}).click();
  await expect(page.locator('#detail-title')).toHaveText('Aluno de demonstração corrigido');
  await page.getByRole('button',{name:'Cancelar certificado',exact:true}).click();
  await page.locator('#confirmation').getByRole('button',{name:'Cancelar certificado',exact:true}).click();
  await expect(page.locator('#details .badge')).toHaveText('Cancelado');
  await page.getByRole('button',{name:'Histórico',exact:true}).click();
  await expect(page.locator('.history li')).toHaveCount(3);
  await page.locator('#close-details').click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'test-results/mobile-admin.png'});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto(url.replace('https://vynkor.co','http://127.0.0.1:8792'));
  await expect(page.getByRole('heading',{name:'Certificado cancelado'})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Aluno de demonstração corrigido'})).toBeVisible();
  await page.screenshot({path:'test-results/mobile-public.png'});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('http://127.0.0.1:8792/certificados/'+'b'.repeat(32));
  await expect(page.getByText('Certificado não encontrado.',{exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});
